def encode_count(value: int) -> bytes:
    if value < ARCHIVE_COUNT_ESCAPE:
        return struct.pack("<H", value)
    return struct.pack("<HI", ARCHIVE_COUNT_ESCAPE, value)


def encode_field(item: tuple) -> bytes:
    kind = item[0]
    if kind == "i":
        return int(item[4]).to_bytes(item[3], "little")
    if kind == "f":
        return struct.pack(
            "<d" if item[2] == "double" else "<f", float.fromhex(item[3])
        )
    if kind == "b":
        return bytes.fromhex(item[3])
    if kind == "s":
        return encode_string(item[2])
    if kind == "c":
        return encode_count(item[2])
    if kind == "t":
        return bytes.fromhex(item[2])
    raise SldprtFormatError(f"unknown declared field kind {kind!r}")


def encode_detail_defs() -> bytes:
    return b"".join(encode_field(item) for item in MODETAILDEFS_C_FIELDS)


def declared_detail_bytes() -> tuple[int, int]:
    declared = 0
    framing = 0
    for item in MODETAILDEFS_C_FIELDS:
        width = len(encode_field(item))
        if item[0] == "t":
            framing += width
        else:
            declared += width
    return declared, framing


def encode_unit_record(entry: tuple) -> bytes:
    return b"".join(encode_field(item) for item in entry[2]) + bytes.fromhex(entry[3])


UNIT_NODE_BODIES = {entry[0]: encode_unit_record(entry) for entry in UNIT_NODE_RECORDS}
UNIT_NODE_SPLIT = {
    entry[0]: (
        sum(len(encode_field(item)) for item in entry[2]),
        len(entry[3]) // 2,
    )
    for entry in UNIT_NODE_RECORDS
}


def declared_unit_bytes() -> tuple[int, int]:
    declared = sum(pair[0] for pair in UNIT_NODE_SPLIT.values())
    residual = sum(pair[1] for pair in UNIT_NODE_SPLIT.values())
    return declared, residual


def encode_detail_region() -> bytes:
    return (
        RESIDUAL_MORELMGR_C_HEAD + encode_detail_defs() + RESIDUAL_MODETAILDEFS_C_TAIL
    )


def detail_region_bodies() -> tuple[bytes, ...]:
    flat = encode_detail_region()
    bodies: list[bytes] = []
    at = 0
    for index, entry in enumerate(DETAIL_REGION_PLAN):
        if index:
            at += 2
        length = entry[3]
        bodies.append(flat[at : at + length])
        at += length
    if at != len(flat):
        raise SldprtFormatError(f"moDetailDefs_c region cut {at} of {len(flat)} bytes")
    return tuple(bodies)


