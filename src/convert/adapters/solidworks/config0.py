def atom_tail(generation: int) -> bytes:
    return struct.pack("<III", generation, ATOM_TAIL_SECOND_WORD, ATOM_TAIL_THIRD_WORD)


def atom_record(atom_id: int, tree_id: int, stamp: int, position: int) -> bytes:
    body = bytearray(ATOM_RECORD_TEMPLATE[:ATOM_RECORD_CORE_LENGTH])
    struct.pack_into("<I", body, ATOM_RECORD_ID_OFFSET, atom_id)
    for offset in ATOM_RECORD_TREE_ID_OFFSETS:
        struct.pack_into("<I", body, offset, tree_id)
    for offset in ATOM_RECORD_SESSION_STAMP_OFFSETS:
        struct.pack_into("<I", body, offset, stamp)
    struct.pack_into("<I", body, ATOM_RECORD_ID_OFFSET + 4, 0 if position == 0 else 1)
    return bytes(body)


def high_water_body(highest: int, next_free: int) -> bytes:
    body = bytearray(NODE_PLAN[HIGH_WATER_POSITION][3])
    struct.pack_into("<II", body, HIGH_WATER_ID_OFFSET, highest, next_free)
    return bytes(body)


def build_nodes(
    part_name: str,
    atoms: tuple[tuple[int, int], ...],
    session_stamp: int,
    generation: int,
    dual_length_units: bool,
    high_water: tuple[int, int],
) -> list[tuple[str, str, int, bytes]]:
    nodes: list[tuple[str, str, int, bytes]] = []
    for position, entry in enumerate(NODE_PLAN):
        kind, class_name, schema, body = entry
        if position == SECONDARY_LENGTH_UNIT_POSITION and not dual_length_units:
            continue
        if position in (
            ATOM_DEFINITION_POSITION + 1,
            ATOM_DEFINITION_POSITION + 2,
        ):
            continue
        if position == PART_NAME_POSITION:
            body = encode_string(part_name) + MO_NODE_SCALARS_AFTER_NAME
        elif position == HIGH_WATER_POSITION:
            body = high_water_body(*high_water)
        nodes.append((kind, class_name, schema, body))
        if position != ATOM_DEFINITION_POSITION:
            continue
        for index, (atom_id, tree_id) in enumerate(atoms):
            if index:
                nodes.append(("classref", "moAtom_c", 0, b""))
            nodes.append(("null", "", 0, ATOM_UNIT_NODE_BODY))
            record = atom_record(atom_id, tree_id, session_stamp, index)
            if index == len(atoms) - 1:
                record += atom_tail(generation)
            nodes.append(("null", "", 0, record))
    return nodes


def assign_indices(nodes: list[tuple[str, str, int, bytes]]) -> list[int]:
    counter = MAP_COUNTER_BASE
    class_index: dict[str, int] = {PROLOGUE_CLASS: 2}
    resolved: list[int] = []
    for kind, class_name, _schema, _body in nodes:
        if kind == "definition":
            class_index[class_name] = counter
            resolved.append(counter)
            counter += 2
        elif kind == "classref":
            resolved.append(class_index[class_name])
            counter += 1
        elif kind == "objectref":
            if class_name.startswith("#"):
                resolved.append(int(class_name[1:]))
            else:
                resolved.append(class_index[class_name] + 1)
        else:
            resolved.append(0)
    return resolved


def encode_config0_stream(
    part_name: str = REFERENCE_PART_NAME,
    atoms: tuple[tuple[int, int], ...] = ((REFERENCE_ATOM_ID, REFERENCE_TREE_ID),),
    session_stamp: int = REFERENCE_SESSION_STAMP,
    generation: int = MO_VERSION,
    dual_length_units: bool = True,
    high_water: tuple[int, int] | None = None,
    part_record_body: bytes = PROLOGUE_BODY_TEMPLATE,
) -> bytes:
    if not atoms:
        raise SldprtFormatError("Contents/Config-0 needs at least one atom record")
    if high_water is None:
        top = max(atom for atom, _tree in atoms)
        high_water = (top, top + 2 * len(atoms))
    nodes = build_nodes(
        part_name,
        tuple(atoms),
        session_stamp,
        generation,
        dual_length_units,
        high_water,
    )
    indices = assign_indices(nodes)
    out = bytearray()
    out += encode_class_definition(PROLOGUE_CLASS, PROLOGUE_SCHEMA)
    out += part_record_body
    for position, (kind, class_name, schema, body) in enumerate(nodes):
        if kind == "definition":
            out += encode_class_definition(class_name, schema)
        elif kind == "classref":
            out += struct.pack("<H", CLASS_TAG_BIT | indices[position])
        elif kind == "objectref":
            out += struct.pack("<H", indices[position])
        else:
            out += b"\x00\x00"
        out += body
    return bytes(out)


def declared_opaque_split(**kwargs: object) -> dict[str, int]:
    stream = encode_config0_stream(**kwargs)
    plan_bodies = {id(entry[3]): position for position, entry in enumerate(NODE_PLAN)}
    styled = set(ANNOTATION_STYLE_NODE_POSITIONS)
    nodes = build_nodes(
        str(kwargs.get("part_name", REFERENCE_PART_NAME)),
        tuple(kwargs.get("atoms", ((REFERENCE_ATOM_ID, REFERENCE_TREE_ID),))),
        int(kwargs.get("session_stamp", REFERENCE_SESSION_STAMP)),
        int(kwargs.get("generation", MO_VERSION)),
        bool(kwargs.get("dual_length_units", True)),
        (REFERENCE_ATOM_ID, REFERENCE_ATOM_ID + 2),
    )
    framing = len(encode_class_definition(PROLOGUE_CLASS, PROLOGUE_SCHEMA))
    declared = len(PROLOGUE_BODY_TEMPLATE)
    opaque = 0
    for kind, class_name, schema, body in nodes:
        framing += (
            len(encode_class_definition(class_name, schema))
            if kind == "definition"
            else 2
        )
        position = plan_bodies.get(id(body), -1)
        if position in styled:
            continue
        if position < 0 or position in (PART_NAME_POSITION,):
            declared += len(body)
        elif position == HIGH_WATER_POSITION:
            declared += 8
            opaque += len(body) - 8
        elif body.startswith(STRING_MARKER):
            head = len(encode_string(read_leading_string(body)))
            declared += head
            opaque += len(body) - head
        else:
            opaque += len(body)
    declared += ANNOTATION_DECLARED_BYTES[0]
    opaque += ANNOTATION_OPAQUE_BYTES[0] + ANNOTATION_STYLE_UNDECODED_BYTES
    return {
        "stream_bytes": len(stream),
        "derived_framing": framing,
        "declared": declared,
        "opaque": opaque,
        "accounted": framing + declared + opaque,
    }


def read_leading_string(body: bytes) -> str:
    units = body[3]
    head = 4
    if units == 0xFF:
        units = struct.unpack_from("<H", body, 4)[0]
        head = 6
    return body[head : head + 2 * units].decode("utf-16-le")
